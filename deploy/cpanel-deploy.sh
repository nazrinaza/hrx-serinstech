#!/bin/bash
# Run by cPanel → Git™ Version Control → "Deploy HEAD Commit" (via .cpanel.yml).
# Copies the code from the Git clone (~/repositories/hrx-serinstech) to the live folder (~/hrx),
# installs PHP packages and updates the database. The live .env and uploaded files are never touched.
#
# Server-specific settings go in ~/.hrx-deploy.conf (not in git), one per line, e.g.
#   HRX_PUBLIC="$HOME/public_html/hr.serinstech.com"
#
#   HRX_LIVE     live app folder                     (default: ~/hrx)
#   HRX_PUBLIC   the domain's existing document root  (default: none, the domain points at ~/hrx/public)
#                When set, the public files are copied there with an index.php that loads ~/hrx.
#   HRX_PHP      PHP 8.3+ binary                      (default: auto-detect)
#   HRX_COMPOSER composer command                     (default: ~/composer.phar, then the usual install paths)
set -euo pipefail

case "$0" in */*) HERE="${0%/*}" ;; *) HERE=. ;; esac
SRC="$(cd "$HERE/.." && pwd)"
# shellcheck source=/dev/null
[[ -f "$HOME/.hrx-deploy.conf" ]] && source "$HOME/.hrx-deploy.conf"
LIVE="${HRX_LIVE:-$HOME/hrx}"
log() { echo "[hrx-deploy] $*"; }

# Copy ~/hrx/public into the domain's own document root (e.g. public_html/hr.serinstech.com),
# keeping the code itself outside public_html. Nothing already there is deleted.
publish_webroot() {
  local web="$1"
  [[ "$web" == "$LIVE"* ]] && { log "ERROR: HRX_PUBLIC must not be inside $LIVE"; exit 1; }
  log "Publishing public files to $web"
  mkdir -p "$web"
  copy_tree "$LIVE/public" "$web" --exclude=index.php --exclude=.htaccess --exclude=storage

  # Front controller that boots the app from ~/hrx and serves public files from here.
  local index
  IFS= read -r -d '' index <<PHP || true
<?php
// Generated by deploy/cpanel-deploy.sh on every deploy: edit that script, not this file.
use Illuminate\Http\Request;

define('LARAVEL_START', microtime(true));
\$root = '$LIVE';

if (file_exists(\$maintenance = \$root.'/storage/framework/maintenance.php')) {
    require \$maintenance;
}

require \$root.'/vendor/autoload.php';

\$app = require_once \$root.'/bootstrap/app.php';
\$app->usePublicPath(__DIR__);
\$app->handleRequest(Request::capture());
PHP
  printf '%s' "$index" > "$web/index.php"

  # Keep cPanel's own .htaccess lines (e.g. the PHP version handler); add Laravel's rules once.
  local current=""
  [[ -f "$web/.htaccess" ]] && current="$(<"$web/.htaccess")"
  if [[ "$current" != *"BEGIN hrx: laravel rules"* ]]; then
    printf '\n# BEGIN hrx: laravel rules\n%s\n# END hrx: laravel rules\n' "$(<"$LIVE/public/.htaccess")" >> "$web/.htaccess"
  fi

  # Company logos (storage/app/public) are served from /storage.
  [[ -e "$web/storage" ]] || ln -s "$LIVE/storage/app/public" "$web/storage"
}

# --- Find PHP 8.3+ (cPanel's CLI `php` is often an older version than the website's).
find_php() {
  local c
  for c in "${HRX_PHP:-}" /opt/cpanel/ea-php83/root/usr/bin/php /opt/cpanel/ea-php84/root/usr/bin/php \
           /opt/alt/php83/usr/bin/php /opt/alt/php84/usr/bin/php php; do
    [[ -z "$c" ]] && continue
    command -v "$c" >/dev/null 2>&1 || continue
    if "$c" -r 'exit(PHP_VERSION_ID >= 80300 ? 0 : 1);' 2>/dev/null; then echo "$c"; return 0; fi
  done
  return 1
}
PHP="$(find_php)" || { log "ERROR: PHP 8.3 or newer not found. Set HRX_PHP in .cpanel.yml."; exit 1; }
log "PHP: $PHP ($("$PHP" -r 'echo PHP_VERSION;'))"
copy_tree() { "$PHP" "$SRC/deploy/sync.php" "$@"; }

# --- Find Composer. Put the chosen PHP first in PATH so `composer` (a `#!/usr/bin/env php` script) uses it.
[[ "$PHP" == */* ]] && export PATH="${PHP%/*}:$PATH"
# cPanel deploys run with a minimal PATH, so also look in the usual install locations.
find_composer() {
  local c
  for c in "$HOME/composer.phar" "$HOME/bin/composer" "$HOME/.local/bin/composer" \
           /opt/cpanel/composer/bin/composer /usr/local/bin/composer /usr/bin/composer \
           "$(command -v composer 2>/dev/null || true)"; do
    [[ -n "$c" && -f "$c" ]] && { echo "$c"; return 0; }
  done
  return 1
}
if [[ -n "${HRX_COMPOSER:-}" ]]; then COMPOSER=($HRX_COMPOSER)
elif C="$(find_composer)"; then
  # A PHP file (composer.phar or `#!/usr/bin/env php`) runs with our PHP 8.3; a shell wrapper runs as is.
  IFS= read -r FIRST < "$C" || true
  if [[ "$FIRST" == *php* ]]; then COMPOSER=("$PHP" "$C"); else COMPOSER=("$C"); fi
else
  log "ERROR: Composer not found. Install it once in cPanel Terminal, then deploy again:"
  log "  cd ~ && curl -sS https://getcomposer.org/installer | $PHP"
  exit 1
fi
log "Composer: ${COMPOSER[*]}"

[[ -f "$SRC/public/build/manifest.json" ]] || { log "ERROR: public/build is missing. Run 'npm run build' and commit it."; exit 1; }

# --- Put the live site in maintenance mode while files change (only once it is installed).
INSTALLED=0
[[ -f "$LIVE/.env" && -f "$LIVE/vendor/autoload.php" ]] && INSTALLED=1
if [[ $INSTALLED == 1 ]]; then
  "$PHP" "$LIVE/artisan" down --retry=15 >/dev/null 2>&1 || true
  trap '"$PHP" "$LIVE/artisan" up >/dev/null 2>&1 || true' EXIT
fi

# --- Copy code (deploy/sync.php: plain PHP, because many cPanel servers have no rsync).
# Files deleted from git are removed from $LIVE too; the excluded paths are never touched.
log "Copying code to $LIVE"
mkdir -p "$LIVE"
copy_tree "$SRC" "$LIVE" --manifest="$LIVE/.hrx-deployed-files" \
  --exclude=.git --exclude=.env --exclude=vendor --exclude=storage --exclude=public/storage \
  --exclude='bootstrap/cache/*.php' --exclude=node_modules --exclude=tests --exclude=database/database.sqlite \
  --exclude=.hrx-deployed-files
# Storage folder skeleton on first deploy; never overwrites logs or uploaded files.
copy_tree "$SRC/storage" "$LIVE/storage" --ignore-existing

cd "$LIVE"
log "Installing PHP packages"
"${COMPOSER[@]}" install --no-dev --optimize-autoloader --no-interaction --no-progress 2>&1 | tail -n 3

[[ -n "${HRX_PUBLIC:-}" ]] && publish_webroot "$HRX_PUBLIC"

if [[ ! -f .env ]]; then
  log "First deploy: code is in place. Next: create $LIVE/.env (see the guide), then finish the install in Terminal."
  exit 0
fi

log "Updating database and caches"
"$PHP" artisan migrate --force
"$PHP" artisan optimize
[[ -e public/storage ]] || "$PHP" artisan storage:link

log "Done: $(cd "$SRC" && git log -1 --format='%h %s' 2>/dev/null || echo 'deployed')"
